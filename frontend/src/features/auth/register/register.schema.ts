import * as Yup from "yup";

// 1. Регулярний вираз для імені (лише літери різних алфавітів, пробіли та дефіси)
export const NAME_REGEXP = /^[A-Za-zА-Яа-яЁёІіЇїЄєҐґ'\s-]+$/;

// 2. Регулярний вираз для email: локальна частина @ домен . TLD (мінімум 2 символи)
export const EMAIL_REGEXP =
  /^(?!\.)(?!.*\.\.)([A-Za-z0-9_'+\-\.]*)[A-Za-z0-9_+-]@([A-Za-z0-9][A-Za-z0-9\-]*\.)+[A-Za-z]{2,}$/;

// 3. Регулярний вираз для складності пароля (мінімум 1 велика, 1 мала, 1 цифра, 1 спецсимвол)
export const PASSWORD_REGEXP = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]+$/;

export const registerSchema = Yup.object({
  name: Yup.string()
    .trim()
    .required("Ім’я є обов’язковим")
    .min(2, "Ім’я має містити щонайменше 2 символи")
    .max(32, "Ім’я має містити не більше 32 символів")
    .matches(NAME_REGEXP, "Ім’я не повинно містити цифр або спеціальних символів"),

  email: Yup.string()
    .trim()
    .required("Email є обов’язковим")
    .max(64, "Email має містити не більше 64 символів")
    .matches(EMAIL_REGEXP, "Некоректний формат email"),

  password: Yup.string()
    .required("Пароль є обов’язковим")
    .min(8, "Пароль має містити щонайменше 8 символів")
    .max(64, "Пароль має містити не більше 64 символів")
    .matches(
      PASSWORD_REGEXP,
      "Пароль має містити щонайменше одну велику літеру, одну малу літеру, одну цифру та один спеціальний символ (@$!%*?&)",
    ),

  confirmPassword: Yup.string()
    .required("Повторіть пароль")
    .oneOf([Yup.ref("password")], "Паролі мають збігатися"),
});
